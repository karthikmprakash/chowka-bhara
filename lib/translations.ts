export function translate(text: string, language: Language): string {
  if (language === "en" || !text.trim()) return text;
  const source = text.trim(),
    prefix = text.slice(0, text.indexOf(source)),
    suffix = text.slice(text.indexOf(source) + source.length);
  const exact = kannada[source];
  if (exact) return prefix + exact + suffix;
  let m: RegExpMatchArray | null;
  if ((m = source.match(/^(\d+) × (\d+) (Classic|Grand)$/)))
    return `${m[1]} × ${m[2]} ${kannada[m[3]]}`;
  if ((m = source.match(/^(.+)’s turn$/))) return `${m[1]} ಅವರ ಸರದಿ`;
  if ((m = source.match(/^(\d+)\/4 home$/))) return `${m[1]}/4 ಮನೆ ಸೇರಿವೆ`;
  if ((m = source.match(/^MOVE (\d+)$/))) return `ನಡೆ ${m[1]}`;
  if ((m = source.match(/^LAST THROW · (\d+)$/))) return `ಹಿಂದಿನ ಅಂಕ · ${m[1]}`;
  if ((m = source.match(/^(\d+) COWRIES$/))) return `${m[1]} ಕವಡೆಗಳು`;
  if (source === "COUNTLESS POSSIBILITIES") return "ಅನೇಕ ಸಾಧ್ಯತೆಗಳು";
  if ((m = source.match(/^You \+ (\d+) computer opponents?$/)))
    return `ನೀವು + ${m[1]} ಕಂಪ್ಯೂಟರ್ ಆಟಗಾರರು`;
  if ((m = source.match(/^Move (\d+) spaces$/)))
    return `${m[1]} ಮನೆ ಮುಂದೆ ಹೋಗಿ`;
  if ((m = source.match(/^Move pawn (\d+)$/))) return `${m[1]}ನೇ ಕಾಯಿ ನಡೆಸಿ`;
  if ((m = source.match(/^(\d+) players$/))) return `${m[1]} ಆಟಗಾರರು`;
  if ((m = source.match(/^(\d+) shells face up$/)))
    return `${m[1]} ಕವಡೆಗಳ ಬಾಯಿ ಮೇಲೆ`;
  if ((m = source.match(/^(\d+) cowrie shells$/))) return `${m[1]} ಕವಡೆಗಳು`;
  if ((m = source.match(/^(\d+) by (\d+) Chowka Bara board$/)))
    return `${m[1]} × ${m[2]} ಚೌಕ ಬಾರ ಮಣೆ`;
  if (
    (m = source.match(
      /^(\d+) shells for this board\. Each open mouth scores 1\. All open scores (\d+); all closed scores (\d+)\. Both earn another throw after your move\.$/,
    ))
  )
    return `ಈ ಮಣೆಗೆ ${m[1]} ಕವಡೆಗಳು. ಪ್ರತಿ ತೆರೆದ ಬಾಯಿಗೆ 1 ಅಂಕ. ಎಲ್ಲ ಬಾಯಿಗಳು ತೆರೆದರೆ ${m[2]} ಅಂಕ; ಎಲ್ಲ ಮುಚ್ಚಿದ್ದರೆ ${m[3]} ಅಂಕ. ಎರಡಕ್ಕೂ ನಿಮ್ಮ ನಡೆಯ ನಂತರ ಮತ್ತೊಂದು ಅವಕಾಶ ಸಿಗುತ್ತದೆ.`;
  if ((m = source.match(/^(.+), pawn (\d+)(?:, move (\d+) spaces)?$/)))
    return `${m[1]}, ಕಾಯಿ ${m[2]}${m[3] ? `, ${m[3]} ಮನೆ ಮುಂದೆ ಹೋಗಿ` : ""}`;
  if ((m = source.match(/^(.+) threw (\d+)(.*)\.$/)))
    return `${m[1]} ${m[2]} ಅಂಕ ಹಾಕಿದರು${m[3] ? " · ಹೆಚ್ಚುವರಿ ಅವಕಾಶ" : ""}.`;
  if ((m = source.match(/^(.+) moved pawn (\d+) by (\d+)\.$/)))
    return `${m[1]} ${m[2]}ನೇ ಕಾಯಿಯನ್ನು ${m[3]} ಮನೆ ನಡೆಸಿದರು.`;
  if ((m = source.match(/^(.+) captured (\d+) pawns?! Throw again\.$/)))
    return `${m[1]} ${m[2]} ಕಾಯಿ ಹೊಡೆದರು! ಮತ್ತೊಮ್ಮೆ ಕವಡೆ ಹಾಕಿ.`;
  if ((m = source.match(/^(.+) brought a pawn home! Throw again\.$/)))
    return `${m[1]} ಒಂದು ಕಾಯಿ ಮನೆ ಸೇರಿಸಿದರು! ಮತ್ತೊಮ್ಮೆ ಕವಡೆ ಹಾಕಿ.`;
  if ((m = source.match(/^(.+) has no legal move\.$/)))
    return `${m[1]} ಅವರಿಗೆ ಯಾವುದೇ ನಡೆ ಇಲ್ಲ.`;
  if ((m = source.match(/^(.+) won the game!$/))) return `${m[1]} ಆಟ ಗೆದ್ದರು!`;
  if ((m = source.match(/^(.+) left the table\.$/)))
    return `${m[1]} ಆಟದಿಂದ ಹೊರಹೋದರು.`;
  if ((m = source.match(/^(.+) wins the courtyard$/)))
    return `${m[1]} ಆಟ ಗೆದ್ದರು`;
  if ((m = source.match(/^Your room code is (.+)$/)))
    return `ನಿಮ್ಮ ಕೋಣೆಯ ಸಂಕೇತ ${m[1]}`;
  if (source.includes(" · "))
    return source
      .split(" · ")
      .map((s) => translate(s, language))
      .join(" · ");
  return text;
}
